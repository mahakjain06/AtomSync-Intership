SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT SHIPMENT_ID || '_' || TIMESTAMP::VARCHAR) AS UNIQUE_READINGS,
    COUNT_IF(TEMPERATURE_C < 0) AS NEGATIVE_TEMPERATURES,
    COUNT_IF(HUMIDITY_PERCENT < 0 OR HUMIDITY_PERCENT > 100) AS INVALID_HUMIDITY,
    COUNT_IF(VIBRATION_G < 0) AS NEGATIVE_VIBRATION
FROM ATMOSYNC_DB.TRANSFORMED.STG_SENSOR_READINGS;