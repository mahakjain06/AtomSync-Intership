CREATE OR REPLACE VIEW ATMOSYNC_DB.TRANSFORMED.SHIPMENT_SUMMARY AS
SELECT
    SHIPMENT_ID,
    COUNT(*) AS TOTAL_READINGS,
    ROUND(AVG(TEMPERATURE_C), 2) AS AVG_TEMPERATURE,
    ROUND(MAX(TEMPERATURE_C), 2) AS MAX_TEMPERATURE,
    ROUND(AVG(HUMIDITY_PERCENT), 2) AS AVG_HUMIDITY,
    ROUND(MAX(VIBRATION_G), 2) AS MAX_VIBRATION
FROM ATMOSYNC_DB.TRANSFORMED.STG_SENSOR_READINGS
GROUP BY SHIPMENT_ID;