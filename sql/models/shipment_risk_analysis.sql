CREATE OR REPLACE VIEW ATMOSYNC_DB.TRANSFORMED.SHIPMENT_RISK_ANALYSIS AS

WITH SHIPMENT_METRICS AS (
    SELECT
        SHIPMENT_ID,
        COUNT(*) AS TOTAL_READINGS,
        AVG(TEMPERATURE_C) AS AVG_TEMPERATURE,
        MAX(TEMPERATURE_C) AS MAX_TEMPERATURE,
        AVG(HUMIDITY_PERCENT) AS AVG_HUMIDITY,
        MAX(HUMIDITY_PERCENT) AS MAX_HUMIDITY,
        AVG(VIBRATION_G) AS AVG_VIBRATION,
        MAX(VIBRATION_G) AS MAX_VIBRATION
    FROM ATMOSYNC_DB.TRANSFORMED.STG_SENSOR_READINGS
    GROUP BY SHIPMENT_ID
)

SELECT
    *,
    CASE
        WHEN MAX_TEMPERATURE > 10
          OR MAX_VIBRATION > 1.5
          OR MAX_HUMIDITY > 90
        THEN 'High'

        WHEN AVG_TEMPERATURE > 8
          OR AVG_VIBRATION > 0.8
        THEN 'Medium'

        ELSE 'Low'
    END AS RISK_LEVEL
FROM SHIPMENT_METRICS;