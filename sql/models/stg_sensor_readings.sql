CREATE OR REPLACE VIEW ATMOSYNC_DB.TRANSFORMED.STG_SENSOR_READINGS AS
SELECT
    UPPER(TRIM(SHIPMENT_ID)) AS SHIPMENT_ID,
    TIMESTAMP,
    ROUND(TEMPERATURE_C, 2) AS TEMPERATURE_C,
    ROUND(HUMIDITY_PERCENT, 2) AS HUMIDITY_PERCENT,
    ROUND(VIBRATION_G, 2) AS VIBRATION_G
FROM ATMOSYNC_DB.RAW_DATA.SENSOR_READINGS
WHERE
    SHIPMENT_ID IS NOT NULL
    AND TIMESTAMP IS NOT NULL
    AND TEMPERATURE_C IS NOT NULL
    AND HUMIDITY_PERCENT IS NOT NULL
    AND VIBRATION_G IS NOT NULL;